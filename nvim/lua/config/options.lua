local opt = vim.opt
local g = vim.g
local o = vim.o

--------------------------------------------------------------------------------
-- Leader Key
--------------------------------------------------------------------------------
g.mapleader = " " -- Space is the leader key

--------------------------------------------------------------------------------
-- Clipboard
--------------------------------------------------------------------------------
-- Defer until after UI ready to avoid blocking startup on provider check.
vim.schedule(function()
	o.clipboard = "unnamedplus"
end)

--------------------------------------------------------------------------------
-- File Backup & Undo
--------------------------------------------------------------------------------
opt.backup = false
opt.swapfile = false
opt.writebackup = false
opt.undodir = vim.fn.stdpath("state") .. "/undo"
o.undofile = true

--------------------------------------------------------------------------------
-- Search
--------------------------------------------------------------------------------
opt.hlsearch = false
opt.incsearch = true
o.ignorecase = true
o.smartcase = true

--------------------------------------------------------------------------------
-- UI Appearance
--------------------------------------------------------------------------------
o.termguicolors = true
opt.colorcolumn = "80"
opt.wrap = false
opt.scrolloff = 8
opt.sidescrolloff = 8
opt.fillchars = { eob = " " }
o.signcolumn = "yes"
o.winborder = "rounded"
o.cursorline = true
o.cursorlineopt = "number"

--------------------------------------------------------------------------------
-- Status & Tabs
--------------------------------------------------------------------------------
o.laststatus = 3
opt.showtabline = 2
opt.showmode = false
o.splitkeep = "screen"

--------------------------------------------------------------------------------
-- Numbers
--------------------------------------------------------------------------------
o.number = true
opt.relativenumber = true
o.numberwidth = 3
o.ruler = false

--------------------------------------------------------------------------------
-- Completion
--------------------------------------------------------------------------------
opt.completeopt = { "menuone", "noselect", "noinsert" }
opt.pumheight = 10
opt.shortmess = opt.shortmess + { c = true }

--------------------------------------------------------------------------------
-- Command Line
--------------------------------------------------------------------------------
opt.cmdheight = 1

--------------------------------------------------------------------------------
-- Indentation
--------------------------------------------------------------------------------
o.expandtab = true
o.shiftwidth = 2
o.smartindent = true
o.tabstop = 2
o.softtabstop = 2

--------------------------------------------------------------------------------
-- Splits
--------------------------------------------------------------------------------
o.splitbelow = true
o.splitright = true

--------------------------------------------------------------------------------
-- Timing
--------------------------------------------------------------------------------
o.updatetime = 250
o.timeoutlen = 300

--------------------------------------------------------------------------------
-- Mouse
--------------------------------------------------------------------------------
o.mouse = "a"

--------------------------------------------------------------------------------
-- Navigation
--------------------------------------------------------------------------------
opt.whichwrap:append("<>[]hl")

--------------------------------------------------------------------------------
-- Disable unused language providers
--------------------------------------------------------------------------------
g.loaded_node_provider = 0
g.loaded_python3_provider = 0
g.loaded_perl_provider = 0
g.loaded_ruby_provider = 0
g.loaded_go_provider = 0
